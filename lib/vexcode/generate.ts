export function driveControl(spec: RobotSpec, devices: Device[]): string {
  const dt = spec.drivetrain;
  const m = (n: string) => devices.find((d) => d.name === n)?.name;
  if (dt.type === 'mecanum' || dt.type === 'xdrive') {
    const lf = m('leftFrontMotor') ?? 'leftFrontMotor', lb = m('leftBackMotor') ?? 'leftBackMotor';
    const rf = m('rightFrontMotor') ?? 'rightFrontMotor', rb = m('rightBackMotor') ?? 'rightBackMotor';
    return [
      '    int fwd = Controller1.Axis3.position();',
      '    int strafe = Controller1.Axis4.position();',
      '    int turn = Controller1.Axis1.position();',
      `    ${lf}.spin(forward, fwd + strafe + turn, percent);`,
      `    ${lb}.spin(forward, fwd - strafe + turn, percent);`,
      `    ${rf}.spin(forward, fwd - strafe - turn, percent);`,
      `    ${rb}.spin(forward, fwd + strafe - turn, percent);`,
    ].join('\n');
  }
  const out = [
    '    leftDrive.spin(forward, Controller1.Axis3.position(), percent);',
    '    rightDrive.spin(forward, Controller1.Axis2.position(), percent);',
  ];
  if (dt.type === 'hdrive') out.push('    strafeMotor.spin(forward, Controller1.Axis4.position(), percent);');
  return out.join('\n');
}

const BUTTONS: Record<string, [string, string] | string> = { intake: ['R1', 'R2'], lift: ['L1', 'L2'] };

export function mechanismControl(spec: RobotSpec, devices: Device[]): { code: string; controls: string[] } {
  const out: string[] = [];
  const controls: string[] = [];
  const target = (subId: string) => {
    const ms = devices.filter((d) => d.subsystemId === subId && d.type === 'motor');
    if (!ms.length) return null;
    return ms[0].group ?? ms[0].name;
  };
  const used = new Set<string>();
  for (const s of spec.subsystems) {
    const t = target(s.id);
    if ((s.type === 'intake' || s.type === 'lift') && t) {
      const [a, b] = BUTTONS[s.type] as [string, string];
      if (used.has(a)) continue;
      used.add(a);
      const stop = s.type === 'lift' ? 'hold' : 'brake';
      out.push(`    if (Controller1.Button${a}.pressing()) {`, `      ${t}.spin(forward, 100, percent);`, `    } else if (Controller1.Button${b}.pressing()) {`, `      ${t}.spin(reverse, 100, percent);`, '    } else {', `      ${t}.stop(${stop});`, '    }');
      controls.push(`| ${a} / ${b} | ${s.name} ${s.type === 'lift' ? 'up / down (hold when released)' : 'in / out (brake when released)'} |`);
    }
  }
  const piston = (type: string, btn: string, label: string) => {
    const p = devices.find((d) => d.type === 'piston' && spec.subsystems.find((s) => s.id === d.subsystemId)?.type === type);
    if (!p || used.has(btn)) return;
    used.add(btn);
    out.push(`    if (Controller1.Button${btn}.pressing()) {`, `      ${p.name}.set(!${p.name}.value());`, `      waitUntil(!Controller1.Button${btn}.pressing());`, '    }');
    controls.push(`| ${btn} | Toggle ${label} |`);
  };
  piston('clamp', 'A', 'the clamp');
  piston('wing', 'B', 'wings');
  const launcher = spec.subsystems.find((s) => s.type === 'launcher');
  if (launcher && target(launcher.id)) {
    out.push('    if (Controller1.ButtonX.pressing()) {', `      ${target(launcher.id)}.spin(forward, 100, percent);`, '    } else {', `      ${target(launcher.id)}.stop(coast);`, '    }');
    controls.push('| X | Fire the launcher |');
  }
  const hang = spec.subsystems.find((s) => s.type === 'hang');
  if (hang) {
    const hp = devices.find((d) => d.subsystemId === hang.id && d.type === 'piston');
    if (hp) { out.push('    if (Controller1.ButtonY.pressing()) {', `      ${hp.name}.set(true);`, '    }'); controls.push('| Y | Hang |'); }
  }
  return { code: out.join('\n'), controls };
}

export function generateMainCpp(spec: RobotSpec, devices: Device[], extraIncludes: string[] = []): string {
  const mech = mechanismControl(spec, devices);
  return `#include "vex.h"
${extraIncludes.map((i) => `#include "${i}"`).join('\n')}${extraIncludes.length ? '\n' : ''}using namespace vex;

competition Competition;

void pre_auton(void) {
  vexcodeInit();
}

void autonomous(void) {
  drive.setDriveVelocity(60, percent);
  drive.setTurnVelocity(40, percent);
  drive.driveFor(forward, 24, inches);
  drive.turnFor(right, 90, degrees);
}

void usercontrol(void) {
  while (true) {
${driveControl(spec, devices)}
${mech.code}
    wait(20, msec);
  }
}

int main() {
  Competition.autonomous(autonomous);
  Competition.drivercontrol(usercontrol);
  pre_auton();
  while (true) {
    wait(100, msec);
  }
}
`;
}

export function controlsMd(spec: RobotSpec, devices: Device[]): string {
  const mech = mechanismControl(spec, devices);
  const drive = spec.drivetrain.type === 'mecanum' || spec.drivetrain.type === 'xdrive'
    ? '| Left stick | Drive + strafe |\n| Right stick (X) | Turn |'
    : '| Left stick (Axis 3) | Left side |\n| Right stick (Axis 2) | Right side |';
  const ports = devices.map((d) => `| ${d.name} | ${d.type}${d.motorType ? ` ${d.motorType}${d.cartridge ? ` ${d.cartridge}` : ''}` : ''} | ${typeof d.port === 'number' ? `PORT${d.port}` : d.port} |`).join('\n');
  return `# ${spec.meta.name} — controls and ports\n\n## Controller\n\n| Buttons | Action |\n|---|---|\n${drive}\n${mech.controls.join('\n')}\n\n## Port map\n\n| Device | Type | Port |\n|---|---|---|\n${ports}\n`;
}

