import type { RobotSpec } from '../robot/spec';
import type { Device } from '../robot/ports';
import { externalRatio, wheelTravelMm } from '../robot/metrics';

const RATIO = { red: 'ratio36_1', green: 'ratio18_1', blue: 'ratio6_1' } as const;

export interface CodeFileGen { path: string; content: string; generated: boolean }

function header(spec: RobotSpec, version: number) {
  return `// AUTO-GENERATED by FDRHS Robotics Hub from "${spec.meta.name}" v${version} — change the build, not this file.`;
}

function motorLine(d: Device) {
  const ratio = d.motorType === '5.5W' ? 'ratio18_1' : RATIO[d.cartridge ?? 'green'];
  const note = d.motorType === '5.5W' ? ' // 5.5 W motor: fixed 200 rpm output (verify gear setting in VEXcode)' : '';
  return `motor ${d.name} = motor(PORT${d.port}, ${ratio}, ${d.reversed ? 'true' : 'false'});${note}`;
}

export function generateRobotConfig(spec: RobotSpec, devices: Device[], version: number): { cpp: string; h: string } {
  const dt = spec.drivetrain;
  const motors = devices.filter((d) => d.type === 'motor');
  const groups = new Map<string, Device[]>();
  for (const m of motors) if (m.group) groups.set(m.group, [...(groups.get(m.group) ?? []), m]);
  const imu = devices.find((d) => d.type === 'inertial');
  const D = dt.wheel.diameterIn;
  const ratio = externalRatio(dt.gearing);
  const travel = wheelTravelMm(D) * ratio;
  const lines: string[] = [];
  const decl: string[] = [];
  lines.push(header(spec, version), '#include "vex.h"', '', 'using namespace vex;', '', '// A global instance of brain used for printing to the V5 Brain screen', 'brain Brain;', 'controller Controller1 = controller(primary);', '');
  decl.push(header(spec, version), '#pragma once', '', 'using namespace vex;', '', 'extern brain Brain;', 'extern controller Controller1;');
  lines.push('// ---- motors ----');
  for (const m of motors) { lines.push(motorLine(m)); decl.push(`extern motor ${m.name};`); }
  if (groups.size) lines.push('', '// ---- motor groups ----');
  for (const [g, ms] of groups) { lines.push(`motor_group ${g} = motor_group(${ms.map((m) => m.name).join(', ')});`); decl.push(`extern motor_group ${g};`); }
  const sensors = devices.filter((d) => ['inertial', 'rotation', 'optical', 'distance', 'gps', 'ai-vision'].includes(d.type));
  if (sensors.length) lines.push('', '// ---- sensors ----');
  for (const s of sensors) {
    switch (s.type) {
      case 'inertial': lines.push(`inertial ${s.name} = inertial(PORT${s.port});`); decl.push(`extern inertial ${s.name};`); break;
      case 'rotation': lines.push(`rotation ${s.name} = rotation(PORT${s.port}, false);`); decl.push(`extern rotation ${s.name};`); break;
      case 'optical': lines.push(`optical ${s.name} = optical(PORT${s.port});`); decl.push(`extern optical ${s.name};`); break;
      case 'distance': lines.push(`distance ${s.name} = distance(PORT${s.port});`); decl.push(`extern distance ${s.name};`); break;
      case 'gps': lines.push(`gps ${s.name} = gps(PORT${s.port}, 0.0, 0.0, mm, 180);`); decl.push(`extern gps ${s.name};`); break;
      case 'ai-vision': lines.push(`// AI Vision on PORT${s.port}: configure it in VEXcode's device menu`); break;
    }
  }
  const tw = devices.filter((d) => d.type === 'piston' || d.type === 'bumper' || d.type === 'limit');
  if (tw.length) lines.push('', '// ---- three-wire ----');
  for (const d of tw) {
    const cls = d.type === 'piston' ? 'digital_out' : d.type;
    lines.push(`${cls} ${d.name} = ${cls}(Brain.ThreeWirePort.${d.port});`);
    decl.push(`extern ${cls} ${d.name};`);
  }
  lines.push('', '// ---- drivetrain ----');
  lines.push(`// WHEEL_TRAVEL_MM is the travel per MOTOR revolution: π × ${D}″ × 25.4 × (${dt.gearing ? `${dt.gearing.driving}/${dt.gearing.driven}` : '1'}) = ${travel.toFixed(2)} mm.`);
  lines.push('// Passing it with externalGearRatio = 1.0 avoids gear-ratio ambiguity.');
  lines.push(`const double WHEEL_TRAVEL_MM = ${travel.toFixed(2)};`);
  lines.push(`const double TRACK_WIDTH_MM = ${(dt.trackWidthIn * 25.4).toFixed(2)};`);
  lines.push(`const double WHEEL_BASE_MM = ${(dt.wheelBaseIn * 25.4).toFixed(2)};`);
  const left = groups.has('leftDrive') ? 'leftDrive' : motors[0]?.name;
  const right = groups.has('rightDrive') ? 'rightDrive' : motors[1]?.name;
  if (imu) {
    lines.push(`smartdrive drive = smartdrive(${left}, ${right}, ${imu.name}, WHEEL_TRAVEL_MM, TRACK_WIDTH_MM, WHEEL_BASE_MM, mm, 1.0);`);
    decl.push('extern smartdrive drive;');
  } else {
    lines.push(`drivetrain drive = drivetrain(${left}, ${right}, WHEEL_TRAVEL_MM, TRACK_WIDTH_MM, WHEEL_BASE_MM, mm, 1.0);`);
    decl.push('extern drivetrain drive;');
  }
  lines.push('', 'void vexcodeInit(void) {');
  if (imu) lines.push(`  Brain.Screen.print("Calibrating inertial...");`, `  ${imu.name}.calibrate();`, `  while (${imu.name}.isCalibrating()) {`, '    wait(50, msec);', '  }', '  Brain.Screen.clearScreen();', '  Brain.Screen.setCursor(1, 1);');
  lines.push(`  Brain.Screen.print("FDRHS ${spec.meta.name.replace(/"/g, '')} ready");`, '}', '');
  decl.push('', 'void vexcodeInit(void);', '');
  return { cpp: lines.join('\n'), h: decl.join('\n') };
}

